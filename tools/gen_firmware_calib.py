#!/usr/bin/env python3
"""Emit the calibration, ignore mask and range fit as a C header.

The on-device scan has to agree with the PC one exactly, so both must come from
the same calibration files rather than from numbers copied by hand. Run this
after any re-calibration and re-flash.

  ./gen_firmware_calib.py            # writes firmware/.../src/scan_calib.h
                                     #    and ros2/.../params/omni_range_calib.yaml

The ROS driver's range_min/range_max are the same thing one step further on: a
LaserScan whose limits disagree with the mirror is a scan whose readings get
silently thrown away by every consumer, so they are generated here too.
"""

import argparse
import json
import os
import sys

import numpy as np

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from omni_common import (CALIB_DIR, PANO_H, PANO_W, N_RAYS, load_calib,
                         load_mask, RangeFit)

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "firmware",
                   "timercam_stream", "src", "scan_calib.h")
ROS_OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "ros2",
                       "toio_omni_range", "params", "omni_range_calib.yaml")

# Radial samples per ray on the device. The annulus is ~87 px wide at 320x320,
# so 100 samples already oversample it; the PC uses 200 panorama rows and the
# run-length parameters are rescaled by RADIAL_N/PANO_H below.
RADIAL_N = 100
SUBRAYS = 5          # angular samples per direction, median-combined


def write_ros_params(path, cal, fit):
    """LaserScan limits for the ROS driver, from the same mirror and fit.

    The limits are the mirror's own horizon (the annulus edges), not the range
    the fit was measured over. A reading between the two is extrapolated but
    real; clipping it away would delete exactly the close obstacles that matter.
    The measured range is written alongside as a comment so the gap stays
    visible when someone reads the file.
    """
    d_in, d_out = (float(v) for v in fit.distance_cm([cal.r_in, cal.r_out]))
    if not (np.isfinite(d_in) and np.isfinite(d_out) and d_out > d_in):
        raise SystemExit("the fit does not resolve the annulus edges "
                         "(r_in=%.1f -> %.2f cm, r_out=%.1f -> %.2f cm). "
                         "Past the arctan horizon the radius carries no distance; "
                         "re-run fit_range.py." % (cal.r_in, d_in, cal.r_out, d_out))

    lines = [
        "# Generated by tools/gen_firmware_calib.py -- do not edit.",
        "# Regenerate after any re-calibration, together with scan_calib.h.",
        "#",
        "# The mirror horizon: r_in=%.1f px -> %.2f cm, r_out=%.1f px -> %.2f cm"
        % (cal.r_in, d_in, cal.r_out, d_out),
        "# The fit was measured over %.1f - %.1f cm; outside that it extrapolates."
        % (fit.d_min or 0.0, fit.d_max or 0.0),
        "/**:",
        "  ros__parameters:",
        "    range_min: %.4f" % (d_in / 100.0),
        "    range_max: %.4f" % (d_out / 100.0),
        "",
    ]
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    with open(path, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s" % path)
    print("  LaserScan range %.3f - %.3f m" % (d_in / 100.0, d_out / 100.0))


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--out", default=OUT)
    ap.add_argument("--ros-out", default=ROS_OUT,
                    help="ROS 2 params file for the LaserScan limits")
    ap.add_argument("--threshold", type=float, default=3.0)
    ap.add_argument("--val-threshold", type=float, default=6.0)
    ap.add_argument("--confirm", type=float, default=4.0)
    ap.add_argument("--min-run", type=int, default=8, help="in PC panorama rows")
    ap.add_argument("--ref-frac", type=float, default=0.5)
    args = ap.parse_args()

    cal = load_calib()
    if not cal.frame_width:
        raise SystemExit("the calibration has no frame_width stamp; re-save it "
                         "with omni_viewer so the device knows what it is for")
    w = int(cal.frame_width)
    c = cal.scaled_to(w)                      # calibration in device pixels
    fit = RangeFit.load()
    if fit is None:
        raise SystemExit("no calib/range_fit.json -- run fit_range.py first")
    if fit.matches(cal) is False:
        raise SystemExit("range_fit.json belongs to a different calibration")

    # PC mask (720 x 200) -> device grid (72 x RADIAL_N), keeping "ignore" if any
    # of the covered PC cells is ignored, so the device is never less careful.
    m = load_mask()
    cols = PANO_W // N_RAYS
    dev = np.ones((N_RAYS, RADIAL_N), bool)
    for i in range(N_RAYS):
        band = m[:, i * cols:(i + 1) * cols]      # (PANO_H, cols)
        usable_row = band.any(axis=1)
        for j in range(RADIAL_N):
            r0 = int(j * PANO_H / RADIAL_N)
            r1 = max(int((j + 1) * PANO_H / RADIAL_N), r0 + 1)
            dev[i, j] = bool(usable_row[r0:r1].all())

    packed = np.packbits(dev, axis=1)             # (72, ceil(RADIAL_N/8))
    min_run_dev = max(1, int(round(args.min_run * RADIAL_N / PANO_H)))

    lines = []
    A = lines.append
    A("// Generated by tools/gen_firmware_calib.py -- do not edit.")
    A("// Regenerate and re-flash after any re-calibration.")
    A("#pragma once")
    A("#include <stdint.h>")
    A("")
    A("#define SCAN_FRAME_W %d" % w)
    A("#define SCAN_FRAME_H %d" % int(cal.frame_height or w))
    A("#define SCAN_N_RAYS %d" % N_RAYS)
    A("#define SCAN_RADIAL_N %d" % RADIAL_N)
    A("#define SCAN_SUBRAYS %d" % SUBRAYS)
    A("")
    A("// geometry, in device pixels")
    A("#define SCAN_CX %.4ff" % c.cx)
    A("#define SCAN_CY %.4ff" % c.cy)
    A("#define SCAN_R_IN %.4ff" % c.r_in)
    A("#define SCAN_R_OUT %.4ff" % c.r_out)
    A("#define SCAN_THETA0_DEG %.4ff" % cal.theta0)
    A("#define SCAN_CCW %d" % (1 if cal.ccw else 0))
    A("")
    A("// detection, matching the PC defaults")
    A("#define SCAN_THRESHOLD %.4ff" % args.threshold)
    A("#define SCAN_VAL_THRESHOLD %.4ff" % args.val_threshold)
    A("#define SCAN_CONFIRM %.4ff" % args.confirm)
    A("#define SCAN_MIN_RUN %d" % min_run_dev)
    A("#define SCAN_REF_FRAC %.4ff" % args.ref_frac)
    A("")
    A("// radius (device px, converted to calibration scale inside) -> cm")
    A("#define SCAN_FIT_A %.6ff" % fit.a)
    A("#define SCAN_FIT_B %.6ff" % fit.b)
    A("#define SCAN_FIT_C %.6ff" % fit.c)
    A("#define SCAN_CALIB_W %.1ff" % 640.0)
    A("#define SCAN_D_MIN %.3ff" % (fit.d_min if fit.d_min else 0.0))
    A("#define SCAN_D_MAX %.3ff" % (fit.d_max if fit.d_max else 999.0))
    A("")
    A("// ignore mask, one bit per (ray, radial sample); 1 = usable")
    A("#define SCAN_MASK_STRIDE %d" % packed.shape[1])
    A("static const uint8_t SCAN_MASK[SCAN_N_RAYS][SCAN_MASK_STRIDE] = {")
    for i in range(N_RAYS):
        A("    {%s}," % ",".join("0x%02x" % v for v in packed[i]))
    A("};")
    A("")

    os.makedirs(os.path.dirname(os.path.abspath(args.out)), exist_ok=True)
    with open(args.out, "w") as f:
        f.write("\n".join(lines))
    print("wrote %s" % args.out)
    print("  frame %dx%d, cx=%.1f cy=%.1f r_in=%.1f r_out=%.1f"
          % (w, cal.frame_height or w, c.cx, c.cy, c.r_in, c.r_out))

    write_ros_params(args.ros_out, cal, fit)
    print("  mask: %.1f%% ignored on the device grid (%.1f%% on the PC grid)"
          % (100 * (~dev).mean(), 100 * (~m).mean()))
    print("  min_run %d PC rows -> %d device samples" % (args.min_run, min_run_dev))


if __name__ == "__main__":
    main()
