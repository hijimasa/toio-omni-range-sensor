#!/usr/bin/env python3
"""Mark everything outside the mat as occupied in a measured map.

A map built by toio_omni_mapping describes what the range sensor saw, and the
sensor cannot see the mat. The mat is paper on a floor: no saturation step at
its edge, so the floor beyond it reads as free space and the map says the robot
may drive there. It may not -- off the mat the Position ID stops and the pose
freezes, which is a worse failure than a collision because nothing reports it.

So the mat boundary is added back as a wall, the same one make_mat_map.py draws
for a mat with no measurements at all. Everything the sensor found *inside* the
mat is kept exactly as measured.

  ./clip_map_to_mat.py --map ../map/arena.yaml

Note this makes the result a planning map, not a localisation map: it claims
walls at the mat edge that the sensor will never see. For AMCL, keep the
unclipped one.
"""

import argparse
import os

import yaml

FREE, OCCUPIED = 254, 0


def read_pgm(path):
    """Return (cols, rows, bytearray) of a binary P5 file."""
    data = open(path, 'rb').read()
    if data[:2] != b'P5':
        raise SystemExit('%s is not a binary PGM' % path)
    fields, i = [], 2
    while len(fields) < 3:
        while data[i:i + 1].isspace():
            i += 1
        if data[i:i + 1] == b'#':
            while data[i:i + 1] != b'\n':
                i += 1
            continue
        j = i
        while not data[j:j + 1].isspace():
            j += 1
        fields.append(int(data[i:j]))
        i = j
    cols, rows, _ = fields
    return cols, rows, bytearray(data[i + 1:i + 1 + cols * rows])


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--map', required=True, help='the measured map yaml')
    ap.add_argument('--params',
                    default=os.path.join(here, '..', 'params',
                                         'toio_a3_folded_left_params.yaml'),
                    help='mat parameters, for the mat size')
    ap.add_argument('--out', help='output basename (default <map>_clipped)')
    args = ap.parse_args()

    with open(args.map) as f:
        meta = yaml.safe_load(f)
    with open(args.params) as f:
        mat = yaml.safe_load(f)['toio_ros2_node']['ros__parameters']
    width_m = float(mat['field_width_meter'])
    height_m = float(mat['field_height_meter'])

    map_dir = os.path.dirname(os.path.abspath(args.map))
    cols, rows, px = read_pgm(os.path.join(map_dir, meta['image']))
    res = float(meta['resolution'])
    ox, oy = float(meta['origin'][0]), float(meta['origin'][1])

    walled = 0
    for row in range(rows):
        # PGM row 0 is the top, which is the largest y.
        y = oy + (rows - row - 0.5) * res
        for col in range(cols):
            x = ox + (col + 0.5) * res
            if 0.0 <= x <= width_m and -height_m <= y <= 0.0:
                continue
            if px[row * cols + col] != OCCUPIED:
                walled += 1
            px[row * cols + col] = OCCUPIED

    out = args.out or os.path.splitext(os.path.abspath(args.map))[0] + '_clipped'
    pgm_path, yaml_path = out + '.pgm', out + '.yaml'
    with open(pgm_path, 'wb') as f:
        f.write(b'P5\n# Generated by tools/clip_map_to_mat.py -- do not edit.\n')
        f.write(b'%d %d\n255\n' % (cols, rows))
        f.write(bytes(px))
    meta['image'] = os.path.basename(pgm_path)
    with open(yaml_path, 'w') as f:
        f.write('# Generated by tools/clip_map_to_mat.py from %s -- do not edit.\n'
                % os.path.basename(args.map))
        f.write('# Everything outside the %.3f x %.3f m mat is a wall: the cube\n'
                '# has no Position ID out there, so it must not be planned into.\n'
                % (width_m, height_m))
        yaml.safe_dump(meta, f, default_flow_style=None, sort_keys=True)

    total = cols * rows
    print('wrote %s and %s' % (pgm_path, yaml_path))
    print('  %d of %d cells turned into wall (%.1f%%), mat %.3f x %.3f m'
          % (walled, total, 100.0 * walled / total, width_m, height_m))


if __name__ == '__main__':
    main()
