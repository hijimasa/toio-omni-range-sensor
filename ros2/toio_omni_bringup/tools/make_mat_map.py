#!/usr/bin/env python3
"""Generate the nav2 occupancy map of a play mat from the toio_ros2 params.

The mat's size already lives in toio_ros2/params/*.yaml, and the ROS pose
conversion already fixes where its corners land in the map frame. Drawing the
map by hand would be a third copy of the same two numbers, and the one that
silently disagrees.

  ./make_mat_map.py                                   # A4, 5 mm cells
  ./make_mat_map.py --params ../../toio_ros2/params/toio_a3_play_mat_params.yaml

The border is occupied rather than unknown on purpose: off the mat the cube
loses the Position ID and stops being localised, so the mat edge really is a
wall as far as planning is concerned.
"""

import argparse
import os

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
DEFAULT_PARAMS = os.path.join(HERE, '..', '..', 'toio_ros2', 'params',
                              'toio_a4_play_mat_params.yaml')
DEFAULT_OUT_DIR = os.path.join(HERE, '..', 'map')

FREE, OCCUPIED = 254, 0


def main():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument('--params', default=DEFAULT_PARAMS,
                    help='toio_ros2 mat parameter file')
    ap.add_argument('--resolution', type=float, default=0.005,
                    help='metres per cell (default 5 mm)')
    ap.add_argument('--border', type=float, default=0.02,
                    help='metres of wall drawn around the mat (default 2 cm)')
    ap.add_argument('--out-dir', default=DEFAULT_OUT_DIR)
    ap.add_argument('--name', help='output basename (default from the params file)')
    args = ap.parse_args()

    with open(args.params) as f:
        params = yaml.safe_load(f)['toio_ros2_node']['ros__parameters']
    width_m = float(params['field_width_meter'])
    height_m = float(params['field_height_meter'])

    name = args.name or os.path.splitext(os.path.basename(args.params))[0]
    name = name.replace('_params', '')

    res, border = args.resolution, args.border
    cols = int(round((width_m + 2 * border) / res))
    rows = int(round((height_m + 2 * border) / res))
    # toio_ros2 puts the mat's near corner at the origin and grows y downwards
    # (convert_toio_to_ros_coord negates it), so the mat covers x in [0, W] and
    # y in [-H, 0].
    origin_x = -border
    origin_y = -height_m - border

    pixels = bytearray(cols * rows)
    inside = 0
    for row in range(rows):
        # PGM row 0 is the top, which is the largest y.
        y = origin_y + (rows - row - 0.5) * res
        for col in range(cols):
            x = origin_x + (col + 0.5) * res
            on_mat = 0.0 <= x <= width_m and -height_m <= y <= 0.0
            pixels[row * cols + col] = FREE if on_mat else OCCUPIED
            inside += on_mat

    os.makedirs(args.out_dir, exist_ok=True)
    pgm_path = os.path.join(args.out_dir, name + '.pgm')
    with open(pgm_path, 'wb') as f:
        f.write(b'P5\n')
        f.write(b'# Generated by tools/make_mat_map.py -- do not edit.\n')
        f.write(b'%d %d\n255\n' % (cols, rows))
        f.write(bytes(pixels))

    yaml_path = os.path.join(args.out_dir, name + '.yaml')
    with open(yaml_path, 'w') as f:
        f.write('# Generated by tools/make_mat_map.py -- do not edit.\n')
        f.write('# Regenerate after changing the mat: it must agree with the\n'
                '# field_*_meter values toio_ros2 is launched with.\n')
        yaml.safe_dump({
            'image': os.path.basename(pgm_path),
            'mode': 'trinary',
            'resolution': res,
            'origin': [origin_x, origin_y, 0.0],
            'negate': 0,
            'occupied_thresh': 0.65,
            'free_thresh': 0.25,
        }, f, default_flow_style=None, sort_keys=True)

    print('wrote %s (%d x %d cells at %.3f m)' % (pgm_path, cols, rows, res))
    print('wrote %s' % yaml_path)
    print('  mat %.3f x %.3f m, origin [%.3f, %.3f], %d free cells'
          % (width_m, height_m, origin_x, origin_y, inside))


if __name__ == '__main__':
    main()
